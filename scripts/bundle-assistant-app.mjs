#!/usr/bin/env node
/**
 * Bundle assistant/worker.mjs for hosted upgrade uploads (no customer wrangler).
 * Writes onboarding/assistant-app-bundle-source.mjs. Run before onboard deploy.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = mkdtempSync(join(tmpdir(), 'lo-asst-bundle-'));
const configPath = join(outdir, 'wrangler.jsonc');
writeFileSync(configPath, JSON.stringify({
  name: 'lo-assistant-bundle',
  main: join(root, 'assistant/worker.mjs'),
  compatibility_date: '2026-11-21',
  compatibility_flags: ['nodejs_compat'],
  ai: { binding: 'AI' }
}, null, 2));

try {
  execFileSync('npx', ['wrangler', 'deploy', '--dry-run', '--outdir', outdir, '--config', configPath], {
    cwd: root, stdio: 'inherit'
  });
  const code = readFileSync(join(outdir, 'worker.js'), 'utf8');
  if (code.length < 10_000 || code.length > 2_000_000) throw Error('unexpected assistant bundle size: ' + code.length);
  const dest = join(root, 'onboarding/assistant-app-bundle-source.mjs');
  writeFileSync(dest,
    '// Generated by scripts/bundle-assistant-app.mjs — do not edit by hand.\n' +
    'export const ASSISTANT_APP_WORKER_MODULE = "worker.js";\n' +
    'export const ASSISTANT_APP_COMPAT_DATE = "2026-11-21";\n' +
    'export const ASSISTANT_APP_COMPAT_FLAGS = Object.freeze(["nodejs_compat"]);\n' +
    'export const ASSISTANT_APP_WORKER_SOURCE = ' + JSON.stringify(code) + ';\n'
  );
  console.log('Wrote', dest, '(' + code.length + ' bytes)');
} finally {
  rmSync(outdir, { recursive: true, force: true });
}
